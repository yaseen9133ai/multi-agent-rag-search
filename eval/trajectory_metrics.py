"""Custom deterministic eval metrics for the multi-agent RAG system.

Why custom metrics instead of the prebuilt `tool_trajectory_avg_score`?
`tool_trajectory_avg_score` compares tool calls **including their arguments**, and it's
all-or-nothing per turn. Our search queries (`search_article`, `exa_search`) are generated by the
LLM and change every run, so an exact-arg trajectory check can never pass reliably for a generative
agent. (Likewise `response_match_score` / ROUGE rarely clears a useful threshold against one
free-form reference.)

So we assert the *stable* signals with a few lines of Python — the "reach for the cheapest criterion
that catches your bug" principle. Three layers, free and deterministic:

  • PROCESS    — `delegated_and_retrieved`   : routed to kb_agent  AND called search_article
                 `routed_to_web_search`      : routed to web_search_agent AND called exa_search
                 (checks tool NAMES, ignores the volatile query arg)
  • RETRIEVAL  — `retrieval_returned_context`: the search tool actually returned non-empty results
                 (reads tool_responses — i.e. what the vector DB / web search handed back)

Answer *quality* (is the answer faithful to what was retrieved?) needs judgement and lives in the
judge suite — `hallucinations_v1` (groundedness) + `final_response_match_v2` (semantic match).

ADK calls a custom metric as
    fn(eval_metric, actual_invocations, expected_invocations, conversation_scenario) -> EvaluationResult
and resolves it from `custom_metrics[...].code_config.name` (e.g. "trajectory_metrics.routed_to_web_search").
"""
from google.adk.evaluation.evaluator import EvaluationResult, PerInvocationResult
from google.adk.evaluation.eval_metrics import EvalStatus

# The search tools whose output counts as "retrieved context".
_SEARCH_TOOLS = {"search_article", "exa_search"}

# Custom metric names defined in this module.
METRIC_NAMES = ("delegated_and_retrieved", "routed_to_web_search", "retrieval_returned_context")


def register():
    """Register this module's custom metrics with ADK's default registry.

    `AgentEvaluator.evaluate()` reads `custom_metrics` from the config to find the function *path*,
    but it does NOT register the metric name in the evaluator registry — so the registry raises
    `NotFoundError: <name> not found in registry` at eval time. Call this once before evaluating
    (conftest.py does it for the tests; compare_to_baseline.py does it for the gate). Idempotent.
    """
    from google.adk.evaluation.metric_evaluator_registry import DEFAULT_METRIC_EVALUATOR_REGISTRY
    from google.adk.evaluation.custom_metric_evaluator import _CustomMetricEvaluator
    from google.adk.evaluation.eval_metrics import MetricInfo, MetricValueInfo

    for name in METRIC_NAMES:
        DEFAULT_METRIC_EVALUATOR_REGISTRY.register_evaluator(
            metric_info=MetricInfo(metric_name=name, metric_value_info=MetricValueInfo()),
            evaluator=_CustomMetricEvaluator,
        )


def _function_calls(invocation):
    """Yield genai FunctionCall objects across one invocation.

    Newer ADK stores the trajectory under `intermediate_data.invocation_events`, each an event with
    `content.parts[].function_call`. Older ADK exposed a flat `intermediate_data.tool_uses` list — we
    fall back to it so this works across versions.
    """
    data = getattr(invocation, "intermediate_data", None)
    if data is None:
        return
    for ev in (getattr(data, "invocation_events", None) or []):
        content = getattr(ev, "content", None)
        for part in (getattr(content, "parts", None) or []):
            fc = getattr(part, "function_call", None)
            if fc is not None:
                yield fc
    for fc in (getattr(data, "tool_uses", None) or []):  # legacy ADK shape
        yield fc


def _function_responses(invocation):
    """Yield genai FunctionResponse objects across one invocation (new + legacy ADK shapes)."""
    data = getattr(invocation, "intermediate_data", None)
    if data is None:
        return
    for ev in (getattr(data, "invocation_events", None) or []):
        content = getattr(ev, "content", None)
        for part in (getattr(content, "parts", None) or []):
            fr = getattr(part, "function_response", None)
            if fr is not None:
                yield fr
    for fr in (getattr(data, "tool_responses", None) or []):  # legacy ADK shape
        yield fr


def _names_and_delegations(invocation):
    """Return (set of tool names called, set of agent_names transferred to) for one invocation."""
    names: set[str] = set()
    agents: set[str] = set()
    for call in _function_calls(invocation):
        name = getattr(call, "name", None)
        if name:
            names.add(name)
        args = getattr(call, "args", None) or {}
        if name == "transfer_to_agent" and args.get("agent_name"):
            agents.add(args["agent_name"])
    return names, agents


def _retrieved_text(invocation) -> str:
    """Concatenate the search tools' RESPONSES (the retrieved chunks / web results) into one string."""
    chunks: list[str] = []
    for resp in _function_responses(invocation):
        if getattr(resp, "name", None) in _SEARCH_TOOLS:
            chunks.append(str(getattr(resp, "response", "") or ""))
    return "\n".join(chunks)


def _result(per_invocation: list) -> EvaluationResult:
    total = sum(r.score for r in per_invocation)
    overall = total / len(per_invocation) if per_invocation else 0.0
    return EvaluationResult(
        overall_score=overall,
        overall_eval_status=EvalStatus.PASSED if overall >= 1.0 else EvalStatus.FAILED,
        per_invocation_results=per_invocation,
    )


def _score_path(actual_invocations, target_agent: str, search_tool: str) -> EvaluationResult:
    out = []
    for inv in actual_invocations:
        names, agents = _names_and_delegations(inv)
        ok = ("transfer_to_agent" in names) and (target_agent in agents) and (search_tool in names)
        out.append(PerInvocationResult(
            actual_invocation=inv,
            score=1.0 if ok else 0.0,
            eval_status=EvalStatus.PASSED if ok else EvalStatus.FAILED,
        ))
    return _result(out)


# ── PROCESS metrics (which branch + did it search) ───────────────────────────
def delegated_and_retrieved(eval_metric, actual_invocations, expected_invocations, conversation_scenario):
    """1.0 if the supervisor delegated to kb_agent AND called search_article. Ignores args."""
    return _score_path(actual_invocations, "kb_agent", "search_article")


def routed_to_web_search(eval_metric, actual_invocations, expected_invocations, conversation_scenario):
    """1.0 if the supervisor delegated to web_search_agent AND called exa_search. Ignores args."""
    return _score_path(actual_invocations, "web_search_agent", "exa_search")


# ── RETRIEVAL-CONTENT metric (did the vector DB / web hand back anything) ─────
def retrieval_returned_context(eval_metric, actual_invocations, expected_invocations, conversation_scenario):
    """1.0 if a search tool returned non-empty results — i.e. retrieval actually grounded on something.

    Reads `tool_responses` (the chunks the vector DB / web search returned), not the answer. This is the
    deterministic half of groundedness: 'did we fetch anything to ground on?'. The judge's
    `hallucinations_v1` is the other half: 'is the answer faithful to it?'.
    """
    out = []
    for inv in actual_invocations:
        text = _retrieved_text(inv)
        ok = len(text) > 40 and "'results': []" not in text and '"results": []' not in text
        out.append(PerInvocationResult(
            actual_invocation=inv,
            score=1.0 if ok else 0.0,
            eval_status=EvalStatus.PASSED if ok else EvalStatus.FAILED,
        ))
    return _result(out)
